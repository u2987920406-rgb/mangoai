const GLUTEN_INGREDIENTS = new Set(["pates", "pain", "farine", "semoule"]);

export function recipeIsGlutenFree(recipe) {
  return !recipe.ingredients.some((id) => GLUTEN_INGREDIENTS.has(id));
}

export function recipeIsQuick(recipe) {
  return recipe.time < 20;
}
